#!/usr/bin/env bun
// Pre-build helper. Reads templates/workflow-worker/*.ts and emits
// src/lib/server/wfp/templates.generated.ts with the contents inlined as
// string constants. The original `?raw` Vite-suffix imports work for the
// SvelteKit build but choke wrangler's esbuild when our worker entry
// (src/worker.ts) reaches the same source files outside the Vite bundle.
// Inlining the strings into a plain TS module makes both bundlers happy.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const templatesDir = path.join(root, 'templates/workflow-worker');
const outFile = path.join(root, 'src/lib/server/wfp/templates.generated.ts');

const sources: Record<string, string> = {
	main: readFileSync(path.join(templatesDir, 'main.ts'), 'utf8'),
	ctx: readFileSync(path.join(templatesDir, 'ctx.ts'), 'utf8'),
	error: readFileSync(path.join(templatesDir, 'error.ts'), 'utf8')
};

function escape(s: string): string {
	return s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

const body = `// AUTO-GENERATED by scripts/generate-templates.ts. Do not edit by hand.
// Re-run via \`bun run scripts/generate-templates.ts\`.
/* eslint-disable */

export const bootstrapMainSource = \`${escape(sources.main)}\`;

export const bootstrapCtxSource = \`${escape(sources.ctx)}\`;

export const bootstrapErrorSource = \`${escape(sources.error)}\`;
`;

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, body, 'utf8');
process.stdout.write(`wrote ${path.relative(root, outFile)}\n`);

// Also (re)create the type stub for the SvelteKit-generated Worker. The
// adapter rimraf's `.svelte-kit/cloudflare/` on every build, so this stub
// must be regenerated alongside templates so `src/worker.ts` type-checks
// against our hand-written signature instead of the auto-generated JS.
const workerDtsPath = path.join(root, '.svelte-kit/cloudflare/_worker.d.ts');
const workerDts = `// AUTO-GENERATED type stub for the SvelteKit Cloudflare Worker. The .js
// peer is regenerated by @sveltejs/adapter-cloudflare on every \`vite build\`
// and does not type-check cleanly under strict mode. This stub gives
// \`src/worker.ts\` a typed default export to import from.
declare const worker: {
\tfetch(req: Request, env: Env, ctx: ExecutionContext): Promise<Response>;
};
export default worker;
`;
mkdirSync(path.dirname(workerDtsPath), { recursive: true });
writeFileSync(workerDtsPath, workerDts, 'utf8');
process.stdout.write(`wrote ${path.relative(root, workerDtsPath)}\n`);
